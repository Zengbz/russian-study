def V(ru,zh,note='重音已标出；听后跟读，再回忆中文。'):return dict(ru=ru,zh=zh,note=note)
def P(ru,zh):return dict(ru=ru,zh=zh)
def C(prompt,answer,options,ex,bucket='理解与运用'):return dict(type='choice',prompt=prompt,answer=answer,options=options,explanation=ex,bucket=bucket,hint='回想本课的字母、词汇与例句，再试一次。')
def L(audio,prompt,answer,options,ex):return dict(type='listen',audio=audio,reveal=audio,prompt=prompt,answer=answer,options=options,explanation=ex,bucket='听力理解')
def I(prompt,answer,ex,mode='translate',audio=None,alts=None,**kw):
    q=dict(type='input',mode=mode,prompt=prompt,answers=[answer]+(alts or []),explanation=ex,bucket='键盘输入',hint=kw.pop('hint','回忆本课对应表达；重音符号可以省略。'),**kw)
    if audio:q.update(audio=audio,reveal=audio)
    if mode=='copy':q.update(reference=answer,practiceOnly=True)
    return q
def M(pairs,prompt='把左边内容与右边对应项配对。',ex='逐项对应后再读一遍。'):return dict(type='match',prompt=prompt,pairs=pairs,explanation=ex,bucket='辨认与配对')
def O(tokens,prompt,ex):return dict(type='order',tokens=tokens,prompt=prompt,explanation=ex,bucket='句子组织')
def S(prompt,checks,reference,ex='说完再对照参考；名字可以换成自己的。'):return dict(type='oral',prompt=prompt,checks=checks,reference=reference,explanation=ex,bucket='开口自检')
